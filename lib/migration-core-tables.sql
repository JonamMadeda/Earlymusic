-- public.songs and public.profiles, the two live tables that had no DDL in
-- this repo. They predate the Neon move and were created out-of-band, so a
-- fresh branch could not be built from the repository. Definitions below were
-- read from production via information_schema/pg_constraint on 2026-11-13 and
-- match prod column-for-column, including the insertion order left behind by
-- past ALTER TABLEs.
--
-- Requires Neon Auth to already own neon_auth."user".

CREATE TABLE IF NOT EXISTS public.songs (
  title               TEXT,
  author              TEXT,
  song_path           TEXT,
  created_at          TIMESTAMPTZ DEFAULT NOW(),
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category            TEXT,
  original_songs      JSONB,
  duration            TEXT,
  copyright_holder    TEXT,
  license_type        TEXT,
  license_url         TEXT,
  rights_clearance_date TIMESTAMPTZ,
  status              TEXT NOT NULL DEFAULT 'approved'
                        CHECK (status IN ('pending', 'approved', 'rejected')),
  region_restricted   BOOLEAN NOT NULL DEFAULT FALSE,
  download_allowed    BOOLEAN NOT NULL DEFAULT TRUE,
  allowed_countries   TEXT[]
);

CREATE INDEX IF NOT EXISTS songs_status_idx ON public.songs USING btree (status);

CREATE TABLE IF NOT EXISTS public.profiles (
  id          UUID PRIMARY KEY,
  first_name  TEXT,
  last_name   TEXT,
  updated_at  TIMESTAMPTZ DEFAULT NOW()
);

-- Guarded so a re-run is a no-op rather than a duplicate-constraint error.
DO $fks$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'public.profiles'::regclass AND conname = 'profiles_id_fkey'
  ) THEN
    ALTER TABLE public.profiles
      ADD CONSTRAINT profiles_id_fkey
      FOREIGN KEY (id) REFERENCES neon_auth."user"(id) ON DELETE CASCADE;
  END IF;
END
$fks$;
